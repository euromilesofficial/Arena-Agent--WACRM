#!/usr/bin/env node
/**
 * fetch-prebuilt.mjs — pull the open-source templates this module ships with.
 *
 * Why a script: the deliverable must open with no network, so every prebuilt
 * template has to be a *file in the repo*. This downloads the source, records
 * provenance (repo, commit, path, licence), strips everything we refuse to
 * execute (scripts, styles, inline handlers, iframes) and writes:
 *
 *   templates/prebuilt/<id>.html   cleaned semantic HTML (committed, auditable)
 *   templates/PROVENANCE.md        source, commit, licence, what changed
 *   src/lib/prebuilt-kits.ts       the same HTML as a typed constant
 *
 * Run: node scripts/fetch-prebuilt.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = { owner: "mmrahmanbappi", repo: "free-html-templates", branch: "main", license: "MIT", homepage: "https://github.com/mmrahmanbappi/free-html-templates" };

const PICKS = [
  ["university", "University", "Education", "education/university"],
  ["language-school", "Language School", "Education", "education/language-school"],
  ["online-course", "Online Course", "Education", "education/online-course"],
  ["tutoring", "Tutoring", "Education", "education/tutoring"],
  ["coding-bootcamp", "Coding Bootcamp", "Education", "education/coding-bootcamp"],
  ["travel-agency", "Travel Agency", "Travel", "real-estate-travel/travel-agency"],
  ["consulting-firm", "Consulting Firm", "Business", "business/consulting-firm"],
  ["creative-agency", "Creative Agency", "Business", "business/creative-agency"],
  ["webinar-signup", "Webinar Signup", "Conversion", "landing-pages/webinar-signup"],
  ["ebook-download", "Ebook Download", "Conversion", "landing-pages/ebook-download"],
  ["product-launch", "Product Launch", "Conversion", "landing-pages/product-launch"],
  ["conference-event", "Conference Event", "Event", "events-community/conference-event"],
  ["nonprofit-charity", "Nonprofit Charity", "Event", "events-community/nonprofit-charity"],
  ["saas-product", "SaaS Product", "Product", "saas-landing/saas-product"]
];

const api = async (url) => {
  const res = await fetch(url, { headers: { "user-agent": "wacrm-cms-build", accept: "application/vnd.github+json" } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
};

/* ---------- cleaning: keep semantics, refuse anything executable ---------- */
function clean(html) {
  let out = html;
  out = out.replace(/<!--[\s\S]*?-->/g, "");
  out = out.replace(/<script[\s\S]*?<\/script>/gi, "");
  out = out.replace(/<style[\s\S]*?<\/style>/gi, "");
  out = out.replace(/<noscript[\s\S]*?<\/noscript>/gi, "");
  out = out.replace(/<(iframe|object|embed|canvas|video|audio|source)\b[\s\S]*?<\/\1>/gi, "");
  out = out.replace(/<(iframe|object|embed|canvas|source)\b[^>]*\/?>/gi, "");
  out = out.replace(/\son[a-z]+\s*=\s*"[^"]*"/gi, "");
  out = out.replace(/\son[a-z]+\s*=\s*'[^']*'/gi, "");
  out = out.replace(/\sstyle\s*=\s*"[^"]*"/gi, "");
  /* body only: the shell of the source page is not content */
  const body = out.match(/<body[^>]*>([\s\S]*)<\/body>/i);
  out = body ? body[1] : out;
  /* collapse whitespace so the bundle stays small */
  out = out.replace(/\s{2,}/g, " ").replace(/>\s+</g, "><").trim();
  /* inline SVG icons are decoration, and they are the bulk of the bytes */
  out = out.replace(/<svg[\s\S]*?<\/svg>/gi, "");
  return out;
}

const head = await api(`https://api.github.com/repos/${SRC.owner}/${SRC.repo}/commits/${SRC.branch}`);
const commit = head.sha.slice(0, 12);

const outDir = path.join(ROOT, "templates", "prebuilt");
fs.mkdirSync(outDir, { recursive: true });

const rows = [];
const kits = [];
for (const [id, name, category, dir] of PICKS) {
  const url = `https://raw.githubusercontent.com/${SRC.owner}/${SRC.repo}/${SRC.branch}/${dir}/index.html`;
  const res = await fetch(url, { headers: { "user-agent": "wacrm-cms-build" } });
  if (!res.ok) { console.error(`skip ${id}: ${res.status}`); continue; }
  const raw = await res.text();
  const cleaned = clean(raw);
  fs.writeFileSync(path.join(outDir, `${id}.html`), cleaned + "\n");
  kits.push({ id, name, category, html: cleaned, source: `${SRC.homepage}/blob/${SRC.branch}/${dir}/index.html`, license: SRC.license, commit });
  rows.push({ id, name, category, dir, raw: raw.length, cleaned: cleaned.length });
  console.log(`· ${id.padEnd(18)} ${String(Math.round(raw.length / 1024)).padStart(4)} KB → ${String(Math.round(cleaned.length / 1024)).padStart(3)} KB`);
}

/* ---------- provenance ---------- */
const md = `# Prebuilt template provenance

Every file in \`templates/prebuilt/\` is derived from an open-source template. This
file is generated by \`scripts/fetch-prebuilt.mjs\`; re-running it re-fetches and
re-records the commit.

**Source:** ${SRC.homepage}
**Licence:** ${SRC.license} (see \`templates/LICENSE-MIT.txt\`) — commercial use permitted, no attribution required in the UI, but we display it anyway.
**Commit fetched:** \`${commit}\`
**What we changed:** removed \`<script>\`, \`<style>\`, \`<noscript>\`, media embeds,
inline \`on*\` handlers, inline \`style=""\` attributes and inline SVG iconography;
kept the body's semantic structure and copy. We take **structure and text only** —
no CSS, no JavaScript, no fonts, no images are copied into the product.

| Template | Category | Source path | Raw | Cleaned |
|---|---|---|---|---|
${rows.map((r) => `| ${r.name} | ${r.category} | \`${r.dir}/index.html\` | ${Math.round(r.raw / 1024)} KB | ${Math.round(r.cleaned / 1024)} KB |`).join("\n")}
`;
fs.writeFileSync(path.join(ROOT, "templates", "PROVENANCE.md"), md);

/* ---------- the typed bundle ---------- */
const ts = `/* ============================================================
   Generated by scripts/fetch-prebuilt.mjs — do not edit by hand.
   ${kits.length} prebuilt templates, ${(kits.reduce((s, k) => s + k.html.length, 0) / 1024).toFixed(0)} KB of cleaned HTML.
   Source: ${SRC.homepage} · ${SRC.license} · commit ${commit}
   The app parses this HTML with the same importer a user's upload goes
   through (src/lib/html-import.ts), so the prebuilt library and the
   import path can never disagree.
   ============================================================ */
export interface PrebuiltKit {
  id: string;
  name: string;
  category: string;
  html: string;
  source: string;
  license: string;
  commit: string;
}

export const PREBUILT_KITS: PrebuiltKit[] = ${JSON.stringify(kits, null, 1)};

export const PREBUILT_SOURCE = { name: "free-html-templates", url: "${SRC.homepage}", license: "${SRC.license}", commit: "${commit}" };
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "prebuilt-kits.ts"), ts);

console.log(`\n${kits.length} kits · ${(kits.reduce((s, k) => s + k.html.length, 0) / 1024).toFixed(0)} KB embedded · commit ${commit}`);
