#!/usr/bin/env node
/* ============================================================
   Refresh the embedded font set for Module 6 · Theme Studio
   ------------------------------------------------------------
   The deliverable is a single HTML file that must work with no
   network and no CDN, and the Typography tab must not claim a
   family it cannot actually render. So the catalogue is embedded:
   real woff2 files, base64, licence-clean (all SIL OFL 1.1).

   Run:  node scripts/fetch-theme-fonts.mjs
   Emits src/lib/theme-font-data.ts + FONT-LICENSES.md
   ============================================================ */
import { writeFileSync } from "node:fs";

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36";

/** Each entry asks the Google Fonts CSS API for what we actually want to ship. */
const WANT = [
  { family: "Geist",      axis: "wght@100..900", css: "Geist:wght@100..900",                weights: [300, 400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Vercel / Basement Studio" },
  { family: "Inter",      axis: "wght@100..900", css: "Inter:wght@100..900",                weights: [300, 400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Rasmus Andersson" },
  { family: "Montserrat", axis: "wght@100..900", css: "Montserrat:wght@100..900",           weights: [300, 400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Julieta Ulanovsky" },
  { family: "DM Sans",    axis: "opsz,wght@9..40,100..1000", css: "DM+Sans:opsz,wght@9..40,100..1000", weights: [300, 400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Colophon Foundry" },
  { family: "Lora",       axis: "wght@400..700", css: "Lora:wght@400..700",                 weights: [400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Cyreal" },
  { family: "Poppins",    axis: "static",       css: "Poppins:wght@400;500;600;700",        weights: [400, 500, 600, 700], license: "SIL Open Font License 1.1", author: "Indian Type Foundry" }
];

const out = [];
let total = 0;

for (const f of WANT) {
  const url = `https://fonts.googleapis.com/css2?family=${f.css}&display=swap`;
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${f.family}: CSS ${res.status}`);
  const css = await res.text();

  /* one @font-face block per subset; latin only — the CMS copy and the EuroMiles
     site are English, and latin-ext would double the embedded bytes for glyphs
     nothing renders */
  const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*{([^}]+)}/g)];
  const faces = [];
  for (const [, subset, body] of blocks) {
    if (subset !== "latin") continue;   // English UI + English public site
    const src = body.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    if (!src) continue;
    const weight = body.match(/font-weight:\s*([^;]+);/)?.[1]?.trim() ?? "400";
    const style = body.match(/font-style:\s*([^;]+);/)?.[1]?.trim() ?? "normal";
    const buf = Buffer.from(await (await fetch(src, { headers: { "User-Agent": UA } })).arrayBuffer());
    total += buf.length;
    faces.push({ subset, weight, style, b64: buf.toString("base64"), bytes: buf.length });
  }
  if (!faces.length) throw new Error(`${f.family}: no woff2 in CSS`);
  const kb = Math.round(faces.reduce((a, x) => a + x.bytes, 0) / 1024);
  console.log(`${f.family.padEnd(12)} ${String(faces.length).padStart(2)} faces  ${String(kb).padStart(4)} KB  ${faces.map((x) => x.subset).join("+")}`);
  out.push({ ...f, faces });
}

const ts = `/* ============================================================
   Module 6 · Theme Studio — embedded font assets
   ------------------------------------------------------------
   GENERATED by scripts/fetch-theme-fonts.mjs — do not edit by hand.
   Real woff2 binaries, base64, so the single-file build renders the
   typography it claims with no network and no CDN. All families are
   SIL OFL 1.1; see FONT-LICENSES.md.
   ${new Date().toISOString().slice(0, 10)} · ${out.length} families · ${Math.round(total / 1024)} KB of woff2
   ============================================================ */

export interface EmbeddedFace { subset: "latin"; weight: string; style: string; b64: string; bytes: number }
export interface EmbeddedFamily {
  family: string; axis: string; /** the Google Fonts CSS request this face set came from */ css: string; weights: number[];
  license: string; author: string; faces: EmbeddedFace[];
}

export const FONT_ASSETS: EmbeddedFamily[] = ${JSON.stringify(out, null, 2)};
`;

writeFileSync("src/lib/theme-font-data.ts", ts);

const lic = `# Font licences — Module 6 · Theme Studio

Every family embedded in \`WACRM-CMS.html\` is licensed under the **SIL Open Font
License 1.1**, which permits embedding in an application, self-hosting and
redistribution, provided the licence travels with the font.

| Family | Weights shipped | Copyright / author | Licence |
|---|---|---|---|
${out.map((f) => `| ${f.family} | ${f.weights.join(", ")} | ${f.author} | SIL OFL 1.1 |`).join("\n")}

Subsets: latin and latin-ext only — the CMS and the EuroMiles site are English.
Total embedded weight: **${Math.round(total / 1024)} KB** as base64 in a single build artefact;
no request ever leaves the document (CSP \`font-src 'self'\` needs nothing external).

Full licence text: https://openfontlicense.org/open-font-license-official-text/

Families that appear in the catalogue but are **not** embedded are shown as
\`Requires ingestion\` and cannot be selected — the UI never pretends to render a
font it does not have.
`;
writeFileSync("FONT-LICENSES.md", lic);
console.log(`\n→ src/lib/theme-font-data.ts (${Math.round(total / 1024)} KB woff2) + FONT-LICENSES.md`);
